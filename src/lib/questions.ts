import { z } from "zod";

const SUBJECT_ID = /^[a-z][a-z-]{1,39}$/;

/** One subject in bank/subjects.json. Topics follow the official JAMB UTME syllabus. */
export const SubjectSchema = z
  .object({
    id: z.string().regex(SUBJECT_ID, "use lowercase letters and hyphens, e.g. \"physics\""),
    name: z.string().min(2).max(60),
    topics: z.array(z.string().min(2).max(64)).min(1),
  })
  .strict();
export type Subject = z.infer<typeof SubjectSchema>;

/** One question in bank/<subject>/<topic>.json. Unknown keys are rejected so typos like "anwser" fail loudly. */
export const QuestionSchema = z
  .object({
    id: z.string().regex(/^[a-z0-9-]+$/, "use lowercase letters, numbers and hyphens").max(64),
    subject: z.string().regex(SUBJECT_ID),
    topic: z.string().min(1).max(64),
    stem: z.string().min(5).max(1500),
    options: z.tuple([z.string().min(1), z.string().min(1), z.string().min(1), z.string().min(1)]),
    /** Index (0-3) of the correct option: 0 = A, 1 = B, 2 = C, 3 = D. */
    answer: z.number().int().min(0).max(3),
    explanation: z.string().min(10).max(1000),
    /**
     * "template": generated by code with a computed answer. "authored": written by a person.
     * "generated": drafted by AI (npm run factory), kept only if a blind second answer agreed, then reviewed by a person in a pull request.
     */
    source: z.enum(["template", "authored", "generated"]),
    /** GitHub username of the person who wrote it, shown as credit in the app. */
    author: z.string().regex(/^[A-Za-z0-9-]{1,39}$/, "must be a GitHub username").optional(),
  })
  .strict();
export type Question = z.infer<typeof QuestionSchema>;

export const LETTERS = ["A", "B", "C", "D"] as const;
