import { z } from "zod";

export const SUBJECTS = {
  english: "Use of English",
  mathematics: "Mathematics",
} as const;
export type SubjectId = keyof typeof SUBJECTS;
export const SUBJECT_IDS = Object.keys(SUBJECTS) as SubjectId[];

// Topics follow the JAMB UTME syllabus sections that v1 covers.
export const TOPICS: Record<SubjectId, readonly string[]> = {
  english: [
    "Synonyms",
    "Antonyms",
    "Sentence completion",
    "Concord",
    "Question tags",
    "Idioms and expressions",
    "Spelling",
  ],
  mathematics: [
    "Number bases",
    "Indices",
    "Logarithms",
    "Percentages and interest",
    "Sets",
    "Linear equations",
    "Quadratic equations",
    "Progressions",
    "Variation",
    "Matrices",
    "Coordinate geometry",
    "Mensuration",
    "Differentiation",
    "Integration",
    "Statistics",
    "Probability",
    "Permutation and combination",
  ],
};

export const QuestionSchema = z.object({
  id: z.string().regex(/^[a-z0-9-]+$/).max(64),
  subject: z.enum(["english", "mathematics"]),
  topic: z.string().min(1).max(64),
  stem: z.string().min(5).max(600),
  options: z.tuple([z.string().min(1), z.string().min(1), z.string().min(1), z.string().min(1)]),
  /** Index (0-3) of the correct option. */
  answer: z.number().int().min(0).max(3),
  explanation: z.string().min(10).max(800),
  /** "template": generated by code with a computed answer. "authored": written and reviewed by hand. */
  source: z.enum(["template", "authored"]),
});
export type Question = z.infer<typeof QuestionSchema>;

export const LETTERS = ["A", "B", "C", "D"] as const;

export function isSubject(value: unknown): value is SubjectId {
  return typeof value === "string" && value in SUBJECTS;
}
